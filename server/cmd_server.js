// =============================================================================
// cmd_server.js  —  the item list the CDM button reads (ONLINE mode)
// =============================================================================
// This file lives on the SERVER (next to armor_server.js / weapon_server.js /
// upgrade_server.js), so players cannot open or edit it. The hidden CDM screen
// (Options -> CDM, unlocked from world chat) searches ONLY this file; it does not
// read weapon_server.js / armor_server.js / upgrade_server.js any more.
//
// WHAT IS IN HERE
//   CMD_WEAPONS        every weapon (swords, gauntlets, guns ...) from weapon_server.js
//   CMD_ARMORS         every armor, ring and accessory from armor_server.js
//   CMD_UPGRADE_ITEMS  every stone and orb from upgrade_server.js (copied as they are)
//
// EVERY weapon / armor / ring / accessory has the FULL stat list below with the
// value 0, so every stat shows up as a row in CDM — type the numbers you want
// there before pressing Get Item / Send:
//   physicalDamage physicalDefense magicalAttack magicalDefense criticalDamage
//   criticalChance health hpRegen manaRegen mana pow vit int dex
// (criticalDamage / criticalChance / hpRegen / manaRegen are fractions: 0.1 = 10%)
// You can also write a real number here to make that item START with that stat,
// or add more numeric stats of your own — every number you add shows in CDM.
//
// SEARCH: in CDM you can type the item's KEY (armor1, sword3, ring05 ...) or its
// NAME (Frostplate Vanguard ...), or part of either. The KEY (the word before the
// colon) is what the game stores in the inventory, so never change a key.
//
// NAMES: change the  name: "..."  line to rename an item. Armors, rings and
// accessories all have names already; weapons keep the names they had.
//
// armor44 exists ONLY here (it was not in armor_server.js): it is not a drop and
// not in shops, you can only get it through CDM.
// =============================================================================

